-- Limpeza: permite rodar o script várias vezes sem erro
BEGIN
  FOR t IN (SELECT table_name FROM user_tables
            WHERE table_name IN ('ALERTA', 'LEITURA', 'CIDADAO', 'REGIAO')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- Tabelas
-- ---------------------------------------------------------------------
CREATE TABLE regiao (
  id_regiao   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nome        VARCHAR2(100) NOT NULL,
  cidade      VARCHAR2(100) NOT NULL,
  estado      CHAR(2)       NOT NULL,
  area_risco  CHAR(1)       DEFAULT 'N' NOT NULL,
  CONSTRAINT pk_regiao PRIMARY KEY (id_regiao),
  CONSTRAINT uk_regiao_nome_cidade UNIQUE (nome, cidade),
  CONSTRAINT ck_regiao_area_risco CHECK (area_risco IN ('S', 'N'))
);

CREATE TABLE cidadao (
  id_cidadao  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nome        VARCHAR2(100) NOT NULL,
  telefone    VARCHAR2(11)  NOT NULL,
  email       VARCHAR2(150) NOT NULL,
  id_regiao   NUMBER        NOT NULL,
  CONSTRAINT pk_cidadao PRIMARY KEY (id_cidadao),
  CONSTRAINT uk_cidadao_email UNIQUE (email),
  CONSTRAINT ck_cidadao_telefone CHECK (LENGTH(telefone) BETWEEN 10 AND 11),
  CONSTRAINT fk_cidadao_regiao FOREIGN KEY (id_regiao) REFERENCES regiao (id_regiao)
);

CREATE TABLE leitura (
  id_leitura  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  tipo        VARCHAR2(20)  NOT NULL,
  valor       NUMBER(6, 2)  NOT NULL,
  data_hora   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  id_regiao   NUMBER        NOT NULL,
  CONSTRAINT pk_leitura PRIMARY KEY (id_leitura),
  CONSTRAINT ck_leitura_tipo CHECK (tipo IN ('CHUVA', 'NIVEL_RIO', 'TEMPERATURA', 'UMIDADE')),
  CONSTRAINT fk_leitura_regiao FOREIGN KEY (id_regiao) REFERENCES regiao (id_regiao)
);

CREATE TABLE alerta (
  id_alerta    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  tipo_evento  VARCHAR2(20)  NOT NULL,
  nivel        VARCHAR2(10)  NOT NULL,
  descricao    VARCHAR2(255) NOT NULL,
  data_hora    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  ativo        CHAR(1)       DEFAULT 'S' NOT NULL,
  id_regiao    NUMBER        NOT NULL,
  CONSTRAINT pk_alerta PRIMARY KEY (id_alerta),
  CONSTRAINT ck_alerta_tipo CHECK (tipo_evento IN ('ENCHENTE', 'DESLIZAMENTO', 'INCENDIO', 'ONDA_CALOR')),
  CONSTRAINT ck_alerta_nivel CHECK (nivel IN ('BAIXO', 'MEDIO', 'ALTO', 'CRITICO')),
  CONSTRAINT ck_alerta_ativo CHECK (ativo IN ('S', 'N')),
  CONSTRAINT fk_alerta_regiao FOREIGN KEY (id_regiao) REFERENCES regiao (id_regiao)
);

