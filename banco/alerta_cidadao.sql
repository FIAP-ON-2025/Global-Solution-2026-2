-- ---------------------------------------------------------------------
-- Consulta: quais regiões estão em risco agora?
-- Regiões com alerta ativo, o nível mais grave e quantos moradores
-- cadastrados devem ser avisados.
-- ---------------------------------------------------------------------
SELECT r.nome                                   AS regiao,
       r.cidade || '/' || r.estado              AS cidade_uf,
       LISTAGG(a.tipo_evento, ', ') WITHIN GROUP (ORDER BY a.tipo_evento) AS riscos,
       CASE MAX(CASE a.nivel WHEN 'BAIXO' THEN 1 WHEN 'MEDIO' THEN 2
                             WHEN 'ALTO' THEN 3 WHEN 'CRITICO' THEN 4 END)
         WHEN 1 THEN 'BAIXO' WHEN 2 THEN 'MEDIO'
         WHEN 3 THEN 'ALTO'  WHEN 4 THEN 'CRITICO'
       END                                      AS nivel_mais_grave,
       (SELECT COUNT(*) FROM cidadao c WHERE c.id_regiao = r.id_regiao) AS moradores_a_avisar
  FROM regiao r
  JOIN alerta a ON a.id_regiao = r.id_regiao
 WHERE a.ativo = 'S'
 GROUP BY r.id_regiao, r.nome, r.cidade, r.estado
 ORDER BY MAX(CASE a.nivel WHEN 'BAIXO' THEN 1 WHEN 'MEDIO' THEN 2
                           WHEN 'ALTO' THEN 3 WHEN 'CRITICO' THEN 4 END) DESC,
          r.nome;
